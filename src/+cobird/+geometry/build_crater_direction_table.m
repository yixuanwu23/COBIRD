function table = build_crater_direction_table(crater)
%BUILD_CRATER_DIRECTION_TABLE Precompute crater aperture distributions.
% Azimuth and elevation use one common angular step; temperature is not
% part of this geometry-only table.

angular_step_deg = 1;
azimuth_count = round(360 / angular_step_deg);
elevation_intervals = round(90 / angular_step_deg);
assert(abs(azimuth_count * angular_step_deg - 360) < 1e-10 && ...
    abs(elevation_intervals * angular_step_deg - 90) < 1e-10, ...
    'cobird:geometry:build_crater_direction_table:step', ...
    'The angular step must divide 90 degrees exactly.');
elevation_count = elevation_intervals + 1;

half_spaces = crater.normal * crater.vertices' - ...
    sum(crater.normal .* crater.centroid, 2);
assert(min(half_spaces, [], 'all') > -1e-9, ...
    'cobird:geometry:build_crater_direction_table:notConvex', ...
    'The aperture-clipping method requires a convex crater cavity.');
sector_count = crater.opts.N_az_mesh;
assert(mod(azimuth_count, sector_count) == 0, ...
    'cobird:geometry:build_crater_direction_table:azimuthCount', ...
    'The azimuth-bin count must be divisible by the crater sector count.');

base_count = azimuth_count / sector_count;
elevation = (0:elevation_intervals) * deg2rad(angular_step_deg);
mu = sin(elevation);
mu(1) = sind(1e-5);
azimuth = (0:base_count-1) * 2 * pi / azimuth_count;
[azimuth_grid, mu_grid] = ndgrid(azimuth, mu);
radius = sqrt(max(0, 1 - mu_grid(:).^2));
directions = [radius .* cos(azimuth_grid(:)), ...
    radius .* sin(azimuth_grid(:)), mu_grid(:)];
base_weights = cobird.geometry.crater_directional_weights(crater, directions);

crater_count = size(crater.normal, 1);
weights = zeros(crater_count, azimuth_count * elevation_count);
for sector = 0:sector_count-1
    angle = sector * 2 * pi / sector_count;
    rotation = [cos(angle), -sin(angle), 0; ...
        sin(angle), cos(angle), 0; 0, 0, 1];
    rotated_centroid = crater.centroid * rotation';
    distance_squared = sum(rotated_centroid.^2, 2) + ...
        sum(crater.centroid.^2, 2)' - 2 * (rotated_centroid * crater.centroid');
    [~, permutation] = min(distance_squared, [], 2);
    assert(numel(unique(permutation)) == crater_count && ...
        max(abs(rotated_centroid - crater.centroid(permutation, :)), [], 'all') < 1e-9 && ...
        max(abs(crater.normal * rotation' - crater.normal(permutation, :)), [], 'all') < 1e-9 && ...
        max(abs(crater.area - crater.area(permutation))) < 1e-10, ...
        'cobird:geometry:build_crater_direction_table:notSymmetric', ...
        'The crater mesh is not rotationally symmetric.');
    columns = (1:base_count)' + sector * base_count + ...
        (0:elevation_count-1) * azimuth_count;
    weights(permutation, columns(:)) = base_weights;
end

rim = crater.vertices(abs(crater.vertices(:, 3)) < 1e-10, 1:2);
aperture_ratio = polyarea(rim(:, 1), rim(:, 2)) / crater.opening_area;
partition_error = max(abs(sum(weights, 1) - aperture_ratio));
assert(partition_error < 2e-7, ...
    'cobird:geometry:build_crater_direction_table:partitionFailure', ...
    'The projected aperture partition error is %.6g.', partition_error);

table = struct( ...
    'schema', 'COBIRD_CRATER_DIRECTION_TABLE', ...
    'weights', weights, ...
    'azimuth_count', azimuth_count, ...
    'elevation_count', elevation_count, ...
    'angular_step_deg', angular_step_deg, ...
    'elevation_step', deg2rad(angular_step_deg), ...
    'horizon_limit_deg', 1e-5, ...
    'aperture_ratio', aperture_ratio, ...
    'partition_error', partition_error, ...
    'crater', crater);
end
