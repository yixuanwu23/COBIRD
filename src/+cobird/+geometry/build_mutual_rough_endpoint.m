function endpoint = build_mutual_rough_endpoint(model, indices, direction)
%BUILD_MUTUAL_ROUGH_ENDPOINT Resolve crater weights on the binary centerline.

direction = direction(:);
indices = double(indices(:));
local_direction = [ ...
    model.x_axis(indices, :) * direction, ...
    model.y_axis(indices, :) * direction, ...
    model.normal(indices, :) * direction];
weights = cobird.geometry.evaluate_crater_direction_table( ...
    model.table, local_direction);

parent_count = numel(model.area);
crater_count = size(model.table.weights, 1);
fraction = model.fraction;
if isscalar(fraction)
    fraction = repmat(fraction, parent_count, 1);
end
endpoint = struct( ...
    'schema', 'COBIRD_MUTUAL_ROUGH_ENDPOINT', ...
    'indices', indices, ...
    'weights', weights, ...
    'fraction', fraction(indices), ...
    'area_ratio', model.table.crater.area(:) / ...
        model.table.crater.opening_area, ...
    'parent_count', parent_count, ...
    'crater_count', crater_count);
end
