function operator = build_rough_exchange_operator( ...
        normal, x_axis, y_axis, area, table, paths)
%BUILD_ROUGH_EXCHANGE_OPERATOR Resolve directional rough terrain exchange.
% Each M2 face pair uses one centroid direction. Emission and reciprocal
% reception share the same aperture distribution.

parent_count = numel(area);
crater_count = size(table.weights, 1);
path_count = numel(paths.i);
assert(numel(paths.j) == path_count && ...
    numel(paths.exchange_area) == path_count && ...
    isequal(size(paths.direction), [path_count, 3]) && ...
    all(paths.i ~= paths.j) && all(paths.i >= 1 & paths.i <= parent_count) && ...
    all(paths.j >= 1 & paths.j <= parent_count) && ...
    all(isfinite(paths.exchange_area) & paths.exchange_area >= 0), ...
    'cobird:geometry:build_rough_exchange_operator:paths', ...
    'Macro exchange paths are invalid.');

parent = [paths.i(:); paths.j(:)];
direction = [paths.direction; -paths.direction];
local_direction = [ ...
    sum(direction .* x_axis(parent, :), 2), ...
    sum(direction .* y_axis(parent, :), 2), ...
    sum(direction .* normal(parent, :), 2)];
assert(all(local_direction(:, 3) > 0), ...
    'cobird:geometry:build_rough_exchange_operator:backFacing', ...
    'Every exchange path must lie above both parent facets.');

block_count = ceil(2 * path_count / 1024);
row_cells = cell(block_count, 1);
column_cells = cell(block_count, 1);
value_cells = cell(block_count, 1);
block = 0;
for first = 1:1024:2 * path_count
    block = block + 1;
    path_index = first:min(first + 1023, 2 * path_count);
    weights = cobird.geometry.evaluate_crater_direction_table( ...
        table, local_direction(path_index, :));
    [crater_index, endpoint, value] = find(weights);
    actual_endpoint = reshape(path_index(endpoint), [], 1);
    row_cells{block} = actual_endpoint;
    column_cells{block} = ...
        (parent(actual_endpoint) - 1) * crater_count + crater_index;
    value_cells{block} = value;
end

distribution = sparse(vertcat(row_cells{:}), vertcat(column_cells{:}), ...
    vertcat(value_cells{:}), 2 * path_count, crater_count * parent_count);
active = find(any(distribution, 1))';
distribution = distribution(:, active);
area_ratio = table.crater.area(:) / table.crater.opening_area;
inverse_area = 1 ./ (area_ratio * area(:)');

operator = struct( ...
    'schema', 'COBIRD_ROUGH_EXCHANGE', ...
    'distribution', distribution, ...
    'active', active, ...
    'inverse_active_area', inverse_area(active), ...
    'parent', parent, ...
    'partner', [(path_count + 1:2 * path_count)'; (1:path_count)'], ...
    'exchange_area', repmat(paths.exchange_area(:), 2, 1), ...
    'area', area(:), ...
    'crater_area_ratio', area_ratio, ...
    'parent_count', parent_count, ...
    'crater_count', crater_count, ...
    'path_count', path_count, ...
    'direction_table_resolution', ...
        [table.azimuth_count, table.elevation_count]);
end
