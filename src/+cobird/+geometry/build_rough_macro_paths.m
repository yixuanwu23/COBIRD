function paths = build_rough_macro_paths(vertices, faces, view_factor)
%BUILD_ROUGH_MACRO_PATHS Build one centroid direction per M2 face pair.

[~, area, centroid] = cobird.geometry.compute_face_geometry(vertices, faces);
assert(strcmp(view_factor.schema, 'M2_VIEW_FACTOR_EXCHANGE') && ...
    view_factor.N_faces == size(faces, 1) && ...
    max(abs(view_factor.area(:) - area) ./ area) < 1e-8, ...
    'cobird:geometry:build_rough_macro_paths:cache', ...
    'The M2 cache does not match the mesh.');

direction = centroid(view_factor.pair_j, :) - centroid(view_factor.pair_i, :);
direction = direction ./ vecnorm(direction, 2, 2);
paths = struct( ...
    'i', view_factor.pair_i(:), ...
    'j', view_factor.pair_j(:), ...
    'direction', direction, ...
    'exchange_area', view_factor.exchange_area(:), ...
    'method', 'M2_one_centroid_direction');
end
