function operator = build_rough_recoil_operator( ...
        normal, x_axis, y_axis, table, shadow)
%BUILD_ROUGH_RECOIL_OPERATOR Integrate directional rough recoil geometry.
% The integral combines crater-wall emission, parent-facet sky visibility,
% and the outgoing direction. It is independent of temperature.

step = 1;
azimuth_count = round(360 / step);
elevation_count = round(90 / step);
assert(abs(azimuth_count * step - 360) < 1e-10 && ...
    abs(elevation_count * step - 90) < 1e-10, ...
    'cobird:geometry:build_rough_recoil_operator:step', ...
    'The angular step must divide 90 degrees exactly.');

parent_count = size(normal, 1);
assert(isequal(size(normal), size(x_axis), size(y_axis)) && ...
    size(normal, 2) == 3, ...
    'cobird:geometry:build_rough_recoil_operator:frameSize', ...
    'Parent-facet frame arrays must have matching N-by-3 sizes.');
assert(isstruct(shadow) && all(isfield(shadow, ...
    {'occ_rev_map', 'shadow_table', 'N_az', 'N_el', 'daz', 'del'})) && ...
    numel(shadow.occ_rev_map) == parent_count, ...
    'cobird:geometry:build_rough_recoil_operator:shadow', ...
    'A matching parent-facet shadow cache is required.');

elevation_edges = (0:elevation_count) * deg2rad(step);
mu = sin((elevation_edges(1:end-1) + elevation_edges(2:end)) / 2);
mu_weight = diff(sin(elevation_edges));
azimuth = ((0:azimuth_count-1) + 0.5) * 2 * pi / azimuth_count;
[azimuth_grid, mu_grid] = ndgrid(azimuth, mu);
radius = sqrt(1 - mu_grid(:).^2);
direction = [radius .* cos(azimuth_grid(:)), ...
    radius .* sin(azimuth_grid(:)), mu_grid(:)];
solid_angle_weight = repmat(mu_weight, azimuth_count, 1) * ...
    (2 * pi / azimuth_count);
projected = cobird.geometry.evaluate_crater_direction_table(table, direction);
projected = projected .* ...
    (direction(:, 3) .* solid_angle_weight(:) / pi)';

crater_count = size(projected, 1);
local_coefficients = zeros(crater_count, parent_count, 3);
for first = 1:32:parent_count
    parent_index = first:min(first + 31, parent_count);
    visible = ones(numel(parent_index), size(direction, 1));
    for row = 1:numel(parent_index)
        face = parent_index(row);
        shadow_row = double(shadow.occ_rev_map(face));
        if shadow_row == 0
            continue
        end
        body_direction = direction(:, 1) * x_axis(face, :) + ...
            direction(:, 2) * y_axis(face, :) + ...
            direction(:, 3) * normal(face, :);
        azimuth_bin = min(shadow.N_az, max(1, floor( ...
            (atan2(body_direction(:, 2), body_direction(:, 1)) + pi) ...
            / shadow.daz) + 1));
        elevation_bin = min(shadow.N_el, max(1, floor( ...
            (asin(max(-1, min(1, body_direction(:, 3)))) + pi / 2) ...
            / shadow.del) + 1));
        bin = (elevation_bin - 1) * shadow.N_az + azimuth_bin;
        visible(row, :) = ~shadow.shadow_table(shadow_row, bin);
    end
    for component = 1:3
        local_coefficients(:, parent_index, component) = ...
            projected * (visible' .* direction(:, component));
    end
end

operator = struct( ...
    'schema', 'COBIRD_ROUGH_RECOIL_INTEGRAL', ...
    'local_coefficients', local_coefficients, ...
    'normal', normal, ...
    'x_axis', x_axis, ...
    'y_axis', y_axis, ...
    'angular_step_deg', step, ...
    'visibility_model', 'parent_centroid_shadow_horizon', ...
    'direction_table_resolution', ...
        [table.azimuth_count, table.elevation_count]);
end
