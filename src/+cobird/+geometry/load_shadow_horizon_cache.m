function cache = load_shadow_horizon_cache(model_root, modelname, expected_azimuth_bins, expected_elevation_bins)
%LOAD_SHADOW_HORIZON_CACHE Load and validate a model's shadow cache.

path = fullfile(model_root, [modelname, '_shadow_horizon.mat']);
cache = load(path);
required = {'schema', 'ray_offset_m', 'N_az', 'N_el', 'daz', 'del', 'occ_faces', ...
    'occ_rev_map', 'shadow_table'};
assert(all(isfield(cache, required)) && ...
    strcmp(cache.schema, 'COBIRD_SHADOW_HORIZON') && ...
    cache.N_az == expected_azimuth_bins && ...
    cache.N_el == expected_elevation_bins && ...
    numel(cache.occ_rev_map) > 0 && ...
    size(cache.shadow_table, 1) == numel(cache.occ_faces) && ...
    size(cache.shadow_table, 2) == cache.N_az * cache.N_el, ...
    'Shadow cache is incomplete or has an incompatible resolution: %s', path);
fprintf('Loaded the shadow-horizon table for %s.\n', modelname);
end
