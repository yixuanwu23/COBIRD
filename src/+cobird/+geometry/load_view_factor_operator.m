function operator = load_view_factor_operator(model_root, modelname)
%LOAD_VIEW_FACTOR_OPERATOR Load a cache and build its sparse exchange operator.

path = fullfile(model_root, [modelname, '_VF.mat']);
data = load(path, 'VF');
view_factor = data.VF;
assert(isfield(view_factor, 'schema') && ...
    strcmp(view_factor.schema, 'M2_VIEW_FACTOR_EXCHANGE'), ...
    'cobird:geometry:load_view_factor_operator:badSchema', ...
    'View-factor cache must be rebuilt with the M2 exchange-area schema: %s', path);
exchange = sparse( ...
    [view_factor.pair_i; view_factor.pair_j], ...
    [view_factor.pair_j; view_factor.pair_i], ...
    [view_factor.exchange_area; view_factor.exchange_area], ...
    view_factor.N_faces, view_factor.N_faces);
operator = spdiags(1 ./ view_factor.area, 0, ...
    view_factor.N_faces, view_factor.N_faces) * exchange;
end
