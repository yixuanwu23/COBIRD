function model = prepare_rough_radiation( ...
        model_root, model_name, vertices, faces, crater, shadow, ...
        fraction, light_speed, terrain_heating)
%PREPARE_ROUGH_RADIATION Build the directional rough-radiation operators.
% The supported model uses one M2 centroid direction per terrain pair.

[normal, area, centroid] = ...
    cobird.geometry.compute_face_geometry(vertices, faces);
[x_axis, y_axis] = ...
    cobird.geometry.build_face_tangent_frame(vertices, faces, normal);
table = cobird.geometry.build_crater_direction_table(crater);
recoil = cobird.geometry.build_rough_recoil_operator( ...
    normal, x_axis, y_axis, table, shadow);
recoil = cobird.geometry.finalize_rough_recoil_operator( ...
    recoil, centroid, area, fraction, light_speed);

exchange = [];
if terrain_heating
    cache_path = fullfile(model_root, [model_name, '_VF.mat']);
    cached = load(cache_path, 'VF');
    assert(isfield(cached, 'VF'), ...
        'cobird:geometry:prepare_rough_radiation:viewFactor', ...
        'The M2 view-factor cache is missing: %s', cache_path);
    paths = cobird.geometry.build_rough_macro_paths( ...
        vertices, faces, cached.VF);
    exchange = cobird.geometry.build_rough_exchange_operator( ...
        normal, x_axis, y_axis, area, table, paths);
end

model = struct( ...
    'contract', cobird.thermal.radiation_model_contract(), ...
    'table', table, ...
    'recoil', recoil, ...
    'exchange', exchange, ...
    'fraction', fraction, ...
    'normal', normal, ...
    'x_axis', x_axis, ...
    'y_axis', y_axis, ...
    'area', area, ...
    'terrain_heating', logical(terrain_heating));
end
