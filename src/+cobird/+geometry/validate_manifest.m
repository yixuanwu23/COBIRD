function entry = validate_manifest(model_root, modelname, expected)
%VALIDATE_MANIFEST Verify a production mesh and all derived geometry caches.
arguments
    model_root (1,:) char
    modelname (1,:) char
    expected struct = struct()
end
manifest_path = fullfile(model_root, 'processed', 'metadata', 'geometry_manifest.json');
assert(isfile(manifest_path), 'cobird:geometry:validate_manifest:missingManifest', ...
    'Geometry manifest not found: %s', manifest_path);
manifest = jsondecode(fileread(manifest_path));
assert(isfield(manifest, 'schema') && strcmp(manifest.schema, 'COBIRD_GEOMETRY_MANIFEST'), ...
    'cobird:geometry:validate_manifest:badSchema', ...
    'The geometry manifest schema is not supported.');
normalized = strrep(modelname, '\', '/');
matches = strcmp({manifest.models.modelname}, normalized);
assert(nnz(matches) == 1, 'cobird:geometry:validate_manifest:modelNotFound', ...
    'Model not found in the geometry manifest: %s', normalized);
entry = manifest.models(matches);
paths = {fullfile(model_root, strrep(entry.obj_file, '/', filesep)), ...
    fullfile(model_root, strrep(entry.reabsorb_file, '/', filesep)), ...
    fullfile(model_root, strrep(entry.shadow_file, '/', filesep)), ...
    fullfile(model_root, strrep(entry.view_factor_file, '/', filesep))};
hashes = {entry.obj_sha256, entry.reabsorb_sha256, entry.shadow_sha256, entry.view_factor_sha256};
kinds = {'OBJ', 'reabsorb', 'shadow horizon', 'view factor'};
for k = 1:numel(paths)
    assert(isfile(paths{k}), 'cobird:geometry:validate_manifest:missingFile', ...
        'Geometry product not found: %s', paths{k});
    actual = cobird.io.compute_file_sha256(paths{k});
    assert(strcmpi(actual, hashes{k}), 'cobird:geometry:validate_manifest:hashMismatch', ...
        '%s %s differs from the geometry manifest. Current=%s, manifest=%s.', ...
        entry.model_id, kinds{k}, actual, hashes{k});
end
[vertices, faces] = cobird.geometry.load_obj_mesh(paths{1});
assert(size(vertices,1) == entry.vertex_count && size(faces,1) == entry.face_count, ...
    'cobird:geometry:validate_manifest:meshSizeMismatch', ...
    '%s vertex or face count differs from the geometry manifest.', entry.model_id);
reabsorb_data = load(paths{2}, 'reabsorb_info');
assert(isfield(reabsorb_data, 'reabsorb_info') && ...
    isfield(reabsorb_data.reabsorb_info, 'method') && ...
    strcmp(reabsorb_data.reabsorb_info.method, 'triangle_horizon'), ...
    'cobird:geometry:validate_manifest:badReabsorptionMethod', ...
    'Rebuild the geometry caches for %s with prepare_model_cache in rebuild mode.', entry.model_id);
shadow_data = load(paths{3}, 'schema', 'ray_offset_m');
assert(isfield(shadow_data, 'schema') && ...
    strcmp(shadow_data.schema, 'COBIRD_SHADOW_HORIZON') && ...
    strcmp(entry.shadow_schema, 'COBIRD_SHADOW_HORIZON') && ...
    shadow_data.ray_offset_m == entry.shadow_ray_offset_m, ...
    'cobird:geometry:validate_manifest:badShadowSchema', ...
    '%s shadow cache does not use the supported ray-direction format.', entry.model_id);
view_factor_data = load(paths{4}, 'VF');
assert(isfield(view_factor_data, 'VF') && ...
    isfield(view_factor_data.VF, 'schema') && ...
    strcmp(view_factor_data.VF.schema, 'M2_VIEW_FACTOR_EXCHANGE') && ...
    strcmp(view_factor_data.VF.method, 'M2_REZAC_ZHAO_2020'), ...
    'cobird:geometry:validate_manifest:badViewFactorSchema', ...
    '%s view-factor cache does not use the M2 exchange-area format.', entry.model_id);
if ~isempty(fieldnames(expected))
    local_validate_setting(expected, 'N_az', entry.shadow_N_az, entry.model_id);
    local_validate_setting(expected, 'N_el', entry.shadow_N_el, entry.model_id);
    local_validate_setting(expected, 'F_threshold', entry.view_factor_F_threshold, entry.model_id);
    local_validate_setting(expected, 'ray_offset_m', entry.view_factor_ray_offset_m, entry.model_id);
end
fprintf('Geometry manifest validation passed: %s (%s...).\n', ...
    entry.model_id, entry.obj_sha256(1:12));
end

function local_validate_setting(expected, name, actual, model_id)
assert(isfield(expected, name), 'cobird:geometry:validate_manifest:missingExpectedSetting', ...
    'Expected parameter expected.%s is missing.', name);
target = expected.(name);
tolerance = 16 * eps(max([1, abs(double(target)), abs(double(actual))]));
assert(abs(double(target) - double(actual)) <= tolerance, ...
    'cobird:geometry:validate_manifest:settingMismatch', ...
    '%s %s mismatch: configured=%g, manifest=%g.', model_id, name, target, actual);
end
