function contract = build_resume_contract(program_id, parameter_file_hash, run_config, extras)
%BUILD_RESUME_CONTRACT Build the immutable configuration contract for restart runs.
assert(isstruct(run_config) && isstruct(extras), ...
    'cobird:runtime:build_resume_contract:invalidInput', ...
    'run_config and extras must be structures.');
mutable_fields = intersect(fieldnames(run_config), ...
    {'duration', 'startup', 'resources', 'validation'}, 'stable');
immutable_config = rmfield(run_config, mutable_fields);
contract = struct('schema', 'COBIRD_RESUME_CONTRACT', ...
    'program_id', char(program_id), ...
    'parameter_file_hash', char(parameter_file_hash), ...
    'run_config', immutable_config, 'extras', extras);
end
