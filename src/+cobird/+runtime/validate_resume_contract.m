function validate_resume_contract(saved, current)
%VALIDATE_RESUME_CONTRACT Verify that a snapshot matches the current setup.
assert(isstruct(saved) && isstruct(current), ...
    'cobird:runtime:validate_resume_contract:invalidInput', ...
    'Resume contracts must be structures.');
required = {'schema', 'program_id', 'parameter_file_hash', 'run_config', 'extras'};
assert(all(isfield(saved, required)), ...
    'cobird:runtime:validate_resume_contract:incompleteSnapshot', ...
    'The snapshot lacks a complete resume contract.');
assert(strcmp(char(saved.schema), char(current.schema)), ...
    'cobird:runtime:validate_resume_contract:contractMismatch', ...
    'Resume contracts do not match.');
assert(strcmp(char(saved.program_id), char(current.program_id)), ...
    'cobird:runtime:validate_resume_contract:programMismatch', ...
    'The snapshot was created by a different production entry point.');
assert(strcmp(char(saved.parameter_file_hash), char(current.parameter_file_hash)), ...
    'cobird:runtime:validate_resume_contract:parameterMismatch', ...
    'The physical-parameter fingerprint differs from the snapshot contract.');
assert(isequaln(saved.run_config, current.run_config), ...
    'cobird:runtime:validate_resume_contract:configMismatch', ...
    'The run configuration differs from the snapshot contract.');
if isfield(current.extras, 'crater_file_sha256')
    assert(isfield(saved.extras, 'crater_file_sha256'), ...
        'cobird:runtime:validate_resume_contract:missingCraterFingerprint', ...
        'The rough-surface snapshot lacks a crater-file fingerprint.');
    assert(strcmp(saved.extras.crater_file_sha256, ...
        current.extras.crater_file_sha256), ...
        'cobird:runtime:validate_resume_contract:craterFingerprintMismatch', ...
        'The crater file differs from the file recorded by the snapshot.');
end
assert(isequaln(saved.extras, current.extras), ...
    'cobird:runtime:validate_resume_contract:geometryMismatch', ...
    'Model, geometry, attitude, or time contracts differ from the snapshot.');
end
