function [T_rough, surface_flux_new] = advance_rough_temperature( ...
    T_rough, params, d_sun_AU, dt, crater, Q_direct, ...
    Q_parent_extra, surface_flux_old, dz, Nz, solver_config)
%ADVANCE_ROUGH_TEMPERATURE Advance explicit hemispherical-crater columns.

crater_count = size(crater.normal, 1);
parent_count = size(Q_direct, 2);
assert(size(T_rough, 1) == parent_count * crater_count, ...
    'cobird:thermal:advance_rough_temperature:temperatureSize', ...
    'T_rough row count does not match the rough geometry.');
assert(isequal(size(Q_direct), [crater_count, parent_count]), ...
    'cobird:thermal:advance_rough_temperature:solarSize', ...
    'Q_direct must be N_crater-by-N_parent.');
assert(isequal(size(Q_parent_extra), [crater_count, parent_count]), ...
    'cobird:thermal:advance_rough_temperature:extraFluxSize', ...
    'External heating must resolve every crater facet.');

assert(isequal(size(surface_flux_old), [crater_count, parent_count]), ...
    'cobird:thermal:advance_rough_temperature:emissionSize', ...
    'surface_flux_old must be N_crater-by-N_parent.');

persistent view_dense_cached view_source_cached
if isempty(view_dense_cached) || ~isequal(view_source_cached, crater.view)
    view_dense_cached = full(crater.view);
    view_source_cached = crater.view;
end

Q_internal_source = params.epsilon .* surface_flux_old + ...
    params.A .* (1 - params.A) .* Q_direct;
Q_internal = view_dense_cached * Q_internal_source;
Q_extra = Q_internal + Q_parent_extra;

mu_flat = Q_direct(:) .* d_sun_AU^2 ./ params.F_s;
Q_extra_flat = Q_extra(:);
if nargout > 1
    [T_rough, surface_flux_flat] = cobird.thermal.advance_temperature_columns( ...
        [], mu_flat, T_rough, params, d_sun_AU, dt, Q_extra_flat, ...
        dz, Nz, solver_config);
    surface_flux_new = reshape(surface_flux_flat, crater_count, parent_count);
else
    T_rough = cobird.thermal.advance_temperature_columns( ...
        [], mu_flat, T_rough, params, d_sun_AU, dt, Q_extra_flat, ...
        dz, Nz, solver_config);
end
end
