function [smooth_heating, rough_heating] = compute_directional_rough_exchange( ...
        operator, smooth_source, rough_source, rough_fraction)
%COMPUTE_DIRECTIONAL_ROUGH_EXCHANGE Resolve directional terrain heating.
% Source and result units are W/m^2 of the corresponding physical surface.

parent_count = operator.parent_count;
crater_count = operator.crater_count;
smooth_source = smooth_source(:);
assert(strcmp(operator.schema, 'COBIRD_ROUGH_EXCHANGE') && ...
    numel(smooth_source) == parent_count && ...
    isequal(size(rough_source), [crater_count, parent_count]), ...
    'cobird:thermal:compute_directional_rough_exchange:size', ...
    'Directional rough-radiation source sizes are incompatible.');
assert(all(isfinite(smooth_source)) && all(isfinite(rough_source), 'all'), ...
    'cobird:thermal:compute_directional_rough_exchange:source', ...
    'Radiative sources must be finite.');
if isscalar(rough_fraction)
    rough_fraction = repmat(rough_fraction, parent_count, 1);
end
rough_fraction = rough_fraction(:);
assert(numel(rough_fraction) == parent_count && ...
    all(rough_fraction >= 0 & rough_fraction <= 1), ...
    'cobird:thermal:compute_directional_rough_exchange:fraction', ...
    'Rough fractions must lie in [0, 1].');

fraction = rough_fraction(operator.parent);
directional_source = operator.distribution * rough_source(operator.active);
outgoing = (1 - fraction) .* smooth_source(operator.parent) + ...
    fraction .* directional_source;
incoming = operator.exchange_area .* outgoing(operator.partner);
smooth_heating = accumarray(operator.parent, incoming, ...
    [parent_count, 1]) ./ operator.area;
rough_heating = zeros(crater_count, parent_count);
rough_heating(operator.active) = ...
    (operator.distribution' * incoming) .* operator.inverse_active_area;
end
