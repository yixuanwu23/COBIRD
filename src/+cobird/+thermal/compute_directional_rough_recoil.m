function [force, moment, per_parent] = compute_directional_rough_recoil( ...
        operator, outgoing_flux)
%COMPUTE_DIRECTIONAL_ROUGH_RECOIL Apply the preintegrated recoil operator.

assert(strcmp(operator.schema, 'COBIRD_ROUGH_RECOIL_OPERATOR') && ...
    isequal(size(outgoing_flux), ...
        [operator.crater_count, operator.parent_count]) && ...
    all(isfinite(outgoing_flux), 'all'), ...
    'cobird:thermal:compute_directional_rough_recoil:state', ...
    'The rough recoil operator or flux is incompatible.');
value = operator.net_map * outgoing_flux(:);
force = value(1:3);
moment = value(4:6);
if nargout > 2
    per_parent = zeros(operator.parent_count, 3);
    for component = 1:3
        per_parent(:, component) = sum( ...
            operator.force_coefficients(:, :, component) .* outgoing_flux, 1)';
    end
end
end
