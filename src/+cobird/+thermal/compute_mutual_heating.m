function [primary_heating, secondary_heating, ...
        primary_rough_heating, secondary_rough_heating] = ...
        compute_mutual_heating( ...
            primary_flux, secondary_flux, primary_rough_flux, ...
            secondary_rough_flux, primary_indices, secondary_indices, ...
            primary_weights, secondary_weights, primary_cosine, ...
            secondary_cosine, primary_endpoint, secondary_endpoint, ...
            emissivity, rough_enabled, reverse_enabled)
%COMPUTE_MUTUAL_HEATING Exchange infrared radiation on the COM centerline.
% Rough emission and reception retain their resolved crater distributions.

if isempty(primary_indices) || isempty(secondary_indices)
    primary_heating = zeros(size(primary_flux));
    secondary_heating = zeros(size(secondary_flux));
    primary_rough_heating = zeros(size(primary_rough_flux));
    secondary_rough_heating = zeros(size(secondary_rough_flux));
    return
end

if rough_enabled
    local_check_endpoint(primary_endpoint, primary_indices, primary_rough_flux);
    local_check_endpoint(secondary_endpoint, secondary_indices, secondary_rough_flux);
    [secondary_heating, secondary_rough_heating] = ...
        cobird.thermal.contract_mutual_direction_mex( ...
            primary_endpoint, secondary_endpoint, primary_flux, ...
            primary_rough_flux, primary_weights, secondary_cosine, emissivity);
    if reverse_enabled
        [primary_heating, primary_rough_heating] = ...
            cobird.thermal.contract_mutual_direction_mex( ...
                secondary_endpoint, primary_endpoint, secondary_flux, ...
                secondary_rough_flux, secondary_weights, primary_cosine, emissivity);
    else
        primary_heating = zeros(size(primary_flux));
        primary_rough_heating = zeros(size(primary_rough_flux));
    end
    return
end

primary_heating = zeros(size(primary_flux));
secondary_heating = zeros(size(secondary_flux));
primary_rough_heating = zeros(size(primary_rough_flux));
secondary_rough_heating = zeros(size(secondary_rough_flux));
secondary_heating(secondary_indices) = emissivity * secondary_cosine * ...
    dot(primary_weights, primary_flux(primary_indices));
if reverse_enabled
    primary_heating(primary_indices) = emissivity * primary_cosine * ...
        dot(secondary_weights, secondary_flux(secondary_indices));
end
end

function local_check_endpoint(endpoint, indices, rough_flux)
assert(isstruct(endpoint) && ...
    strcmp(endpoint.schema, 'COBIRD_MUTUAL_ROUGH_ENDPOINT') && ...
    isequal(endpoint.indices, double(indices(:))) && ...
    isequal(size(rough_flux), ...
        [endpoint.crater_count, endpoint.parent_count]), ...
    'cobird:thermal:compute_mutual_heating:endpoint', ...
    'Directional mutual-radiation geometry is missing or stale.');
end
