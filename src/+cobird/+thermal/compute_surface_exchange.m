function [smooth_heating, rough_heating] = compute_surface_exchange( ...
        model, smooth_exchange, thermal_flux, rough_flux, ...
        reflected_flux, rough_reflected_flux, params, ...
        rough_enabled, terrain_enabled)
%COMPUTE_SURFACE_EXCHANGE Apply the shared within-body exchange model.

parent_count = numel(thermal_flux);
if rough_enabled
    assert(isstruct(model) && ...
        isequal(model.contract, cobird.thermal.radiation_model_contract()) && ...
        model.terrain_heating == logical(terrain_enabled), ...
        'cobird:thermal:compute_surface_exchange:model', ...
        'The directional rough-radiation model is missing or incompatible.');
end
if ~terrain_enabled
    smooth_heating = zeros(parent_count, 1);
    if rough_enabled
        rough_heating = zeros(size(rough_flux));
    else
        rough_heating = [];
    end
    return
end

smooth_source = params.epsilon * thermal_flux + ...
    (1 - params.A) * reflected_flux;
if rough_enabled
    rough_source = params.epsilon * rough_flux + ...
        (1 - params.A) * rough_reflected_flux;
    [smooth_heating, rough_heating] = ...
        cobird.thermal.compute_directional_rough_exchange( ...
            model.exchange, smooth_source, rough_source, model.fraction);
else
    assert(isequal(size(smooth_exchange), [parent_count, parent_count]), ...
        'cobird:thermal:compute_surface_exchange:cache', ...
        'The smooth M2 exchange operator is missing.');
    smooth_heating = smooth_exchange * smooth_source;
    rough_heating = [];
end
end
