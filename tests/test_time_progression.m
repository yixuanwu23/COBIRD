function setupOnce(~)
test_root = fileparts(mfilename('fullpath'));
project_root = fileparts(test_root);
addpath(fullfile(project_root, 'src'));
end

function testThermalSaveStrideDoesNotChangeEvolution(test_case)
problem = struct( ...
    'initial_temperature', 10, ...
    'evaluate_forcing', @(time_s, temperature) time_s + temperature, ...
    'advance_temperature', ...
        @(~, temperature, forcing, dt) temperature + dt * forcing);
dense = cobird.run_thermal(problem, ...
    time_step_s=1, step_count=5, save_stride=1);
sparse_output = cobird.run_thermal(problem, ...
    time_step_s=1, step_count=5, save_stride=3);
verifyEqual(test_case, sparse_output.final_temperature, ...
    dense.final_temperature);
verifyEqual(test_case, sparse_output.time_s, [0; 3; 5]);
verifyEqual(test_case, numel(sparse_output.temperature), 3);
end

function testCoupledStatesUseOneIntervalStart(test_case)
problem = struct( ...
    'initial_state', 2, ...
    'initial_temperature', 3, ...
    'evaluate_radiation', @(~, state, temperature) state + temperature, ...
    'advance_state', @(~, state, radiation, dt) state + dt * radiation, ...
    'advance_temperature', ...
        @(~, temperature, radiation, dt) temperature + dt * radiation);
result = cobird.run_coupled(problem, ...
    time_step_s=1, step_count=2, save_stride=2);
verifyEqual(test_case, result.final_state, 22);
verifyEqual(test_case, result.final_temperature, 23);
verifyEqual(test_case, result.time_s, [0; 2]);
end

function testRoughResumeRequiresMatchingCrater(test_case)
base = cobird.runtime.build_resume_contract( ...
    'coupled', 'parameters', struct(), ...
    struct('crater_file_sha256', 'abc'));
missing = base;
missing.extras = struct();
verifyError(test_case, @() cobird.runtime.validate_resume_contract(missing, base), ...
    'cobird:runtime:validate_resume_contract:missingCraterFingerprint');
mismatch = base;
mismatch.extras.crater_file_sha256 = 'def';
verifyError(test_case, @() cobird.runtime.validate_resume_contract(mismatch, base), ...
    'cobird:runtime:validate_resume_contract:craterFingerprintMismatch');
cobird.runtime.validate_resume_contract(base, base);
end
